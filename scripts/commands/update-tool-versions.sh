#!/usr/bin/env bash
# Refresh core tools and GitHub Actions from upstream releases and open one PR.
#
# Intended to run from CI (update-tools workflow) with a GitHub token that has
# contents:write and pull-requests:write. Exits 0 when nothing changed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

BRANCH="automation/dependency-updates"

push_update_branch() {
  local remote_sha
  remote_sha="$(git ls-remote origin "refs/heads/${BRANCH}" | awk 'NR == 1 { print $1 }')"
  if [ -n "$remote_sha" ]; then
    git push -u --force-with-lease="refs/heads/${BRANCH}:${remote_sha}" origin "$BRANCH"
  else
    git push -u origin "$BRANCH"
  fi
}

ensure_update_pull_request() {
  local title="$1"
  local body="$2"
  local pr_number pr_output compare_url

  pr_number="$(gh pr list --head "$BRANCH" --state open --json number --jq '.[0].number // empty' 2>/dev/null || true)"
  if [ -n "$pr_number" ]; then
    echo "pull request #${pr_number} already open for ${BRANCH}; branch updated"
    return 0
  fi

  if pr_output="$(gh pr create --base main --head "$BRANCH" --title "$title" --body "$body" 2>&1)"; then
    printf '%s\n' "$pr_output"
    return 0
  fi

  if [[ "$pr_output" == *"not permitted to create or approve pull requests"* ]]; then
    compare_url="${GITHUB_SERVER_URL:-https://github.com}/${GITHUB_REPOSITORY:-KuGouGo/Rules}/compare/main...${BRANCH}?expand=1"
    echo "::warning::GitHub Actions cannot create pull requests for this repository; the validated update branch was pushed."
    echo "Create the pull request manually: $compare_url"
    return 0
  fi

  printf 'pull request creation failed: %s\n' "$pr_output" >&2
  return 1
}

validate_update_branch() {
  local head_sha run_id="" attempt

  head_sha="$(git rev-parse HEAD)"
  gh workflow run validate.yml --ref "$BRANCH"

  for attempt in {1..12}; do
    run_id="$(gh run list --workflow validate.yml --branch "$BRANCH" \
      --event workflow_dispatch --limit 10 --json databaseId,headSha \
      --jq '.[] | select(.headSha == "'"$head_sha"'") | .databaseId' |
      head -n 1)"
    [ -n "$run_id" ] && break
    echo "waiting for dispatched validation run (${attempt}/12)"
    sleep 5
  done

  if [ -z "$run_id" ]; then
    echo "dispatched validation run was not found for ${head_sha}" >&2
    return 1
  fi

  echo "waiting for validation run ${run_id} on ${BRANCH}"
  gh run watch "$run_id" --exit-status
}

main() {
  local tool_output action_output versions title body

  cd "$ROOT"
  tool_output="$(python3 "$ROOT/scripts/tools/update-tool-lock.py" --root "$ROOT")"
  action_output="$(python3 "$ROOT/scripts/tools/update-action-pins.py" --root "$ROOT")"
  printf '%s\n' "$tool_output"
  printf '%s\n' "$action_output"

  if ! grep -q '^changed=true$' <<< "$tool_output" &&
    ! grep -q '^changed=true$' <<< "$action_output"; then
    echo "no dependency updates available"
    return 0
  fi

  # Validate the refreshed release binaries before proposing them: verify
  # archive + binary digests and version probes, run the full test suite, and
  # compile deterministic custom artifacts with both tools.
  # shellcheck source=scripts/lib/common.sh
  source "$ROOT/scripts/lib/common.sh"
  setup_tool_cache
  ensure_sing_box
  ensure_mihomo
  REQUIRE_SHELLCHECK=1 make validate-tool-update

  versions="$(printf '%s\n%s\n' "$tool_output" "$action_output" |
    sed -n 's/^versions=//p' | paste -sd '|' - | sed 's/|/, /g')"
  [ -n "$versions" ] || versions="dependencies"
  title="chore: update dependencies (${versions})"

  git config user.name "github-actions[bot]"
  git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
  git checkout -B "$BRANCH"
  git add config/tools-lock.json .github/actions .github/workflows \
    scripts/tests/test-tool-lock.sh scripts/tests/test-upstream-config.sh
  git commit -m "${title}" -m "Auto-generated by the update-tool-versions workflow.

Digests and tag commits were computed from the upstream release assets. The
refreshed lock was validated locally (archive + binary SHA-256 checks and
version probes) before this branch was created."

  body="Auto-generated by the update-tool-versions workflow.

Updated dependencies: ${versions}.

The refreshed lock was validated (archive + binary SHA-256 checks and version
probes) before this branch was created."
  push_update_branch
  ensure_update_pull_request "$title" "$body"
  validate_update_branch
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
